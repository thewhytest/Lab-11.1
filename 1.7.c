#include <stdio.h>

#define N 10

int main(void)
{
    float A[N];      // исходный массив
    float B[N];      // преобразованный массив
    float temp;
    float c;         // константа, на которую уменьшаем
    float sum = 0.0f;

    // Ввод константы
    printf("Введите константу c: ");
    scanf("%f", &c);

    // Ввод массива с консоли
    for (int i = 0; i < N; i++)
    {
        printf("a[%d] = ", i + 1);
        scanf("%f", &temp);
        A[i] = temp;
    }

    // Преобразование: уменьшить каждый элемент на константу
    for (int i = 0; i < N; i++)
    {
        B[i] = A[i] - c;
    }

    // Вывод таблицы
    printf("\n| %-6s | %-17s | %-14s |\n", "индекс", "исходное значение", "новое значение");
    printf("|--------|-------------------|----------------|\n");
    for (int i = 0; i < N; i++)
    {
        printf("| %-6d | %-17.2f | %-14.2f |\n", i + 1, A[i], B[i]);
    }

    // Среднее арифметическое
    for (int i = 0; i < N; i++)
        sum += B[i];

    printf("\nСреднее арифметическое: %.2f\n", sum / N);

    return 0;
}
